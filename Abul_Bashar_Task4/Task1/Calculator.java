public class Calculator {

    // Method 1: Sum of two integers
    public int compute(int a, int b) {
        return a + b;
    }

    // Method 2: Product of three integers
    public int compute(int a, int b, int c) {
        return a * b * c;
    }

    // Method 3: Division of two numbers
    public double compute(double a, int b) {
        return a / b;
    }

    // Method 4: Average of three numbers
    public double compute(double a, double b, double c) {
        return (a + b + c) / 3;
    }
}
